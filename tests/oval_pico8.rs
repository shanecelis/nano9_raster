#![cfg(feature = "ellipse")]

//! Pico-8 ground-truth bit patterns for `oval` / `ovalfill`.
//!
//! Captured from `nano9/tests/golden/oval-small.p8` (`oval-small-expected.png`).
//! Inclusive corners: `Ellipse::from_rect((x0, y0), (x1, y1))` matches Pico-8
//! `oval(x0, y0, x1, y1)` / `ovalfill`. Each case is translated so the Pico-8
//! bounding rect starts at `(0, 0)`.
//!
//! Rows are packed MSB = x = 0 via `plot_bits` / `plot_spans`.

mod common;
#[cfg(feature = "fill")]
use common::plot_spans;
use common::{assert_bitmap_eq, plot_bits};
use nano9_raster::Ellipse;

/// Pico-8 `oval(8, 32, 8, 32)`.
#[test]
fn pico_oval_1x1() {
    #[rustfmt::skip]
    assert_bitmap_eq!(plot_bits::<1>(Ellipse::from_rect((0, 0), (0, 0)), 1), [
        0b1, // #
    ], 1);
}

/// Pico-8 `oval(16, 32, 20, 36)`.
#[test]
fn pico_oval_5x5() {
    #[rustfmt::skip]
    assert_bitmap_eq!(plot_bits::<5>(Ellipse::from_rect((0, 0), (4, 4)), 5), [
        0b01110, // .###.
        0b10001, // #...#
        0b10001, // #...#
        0b10001, // #...#
        0b01110, // .###.
    ], 5);
}

/// Pico-8 `oval(28, 32, 40, 40)`.
#[test]
fn pico_oval_13x9() {
    #[rustfmt::skip]
    assert_bitmap_eq!(plot_bits::<9>(Ellipse::from_rect((0, 0), (12, 8)), 13), [
        0b0000111110000, // ....#####....
        0b0011000001100, // ..##.....##..
        0b0100000000010, // .#.........#.
        0b1000000000001, // #...........#
        0b1000000000001, // #...........#
        0b1000000000001, // #...........#
        0b0100000000010, // .#.........#.
        0b0011000001100, // ..##.....##..
        0b0000111110000, // ....#####....
    ], 13);
}

/// Pico-8 `oval(48, 32, 70, 44)`.
#[test]
fn pico_oval_23x13() {
    #[rustfmt::skip]
    assert_bitmap_eq!(plot_bits::<13>(Ellipse::from_rect((0, 0), (22, 12)), 23), [
        0b00000001111111110000000, // .......#########.......
        0b00001110000000001110000, // ....###.........###....
        0b00010000000000000001000, // ...#...............#...
        0b01100000000000000000110, // .##.................##.
        0b01000000000000000000010, // .#...................#.
        0b10000000000000000000001, // #.....................#
        0b10000000000000000000001, // #.....................#
        0b10000000000000000000001, // #.....................#
        0b01000000000000000000010, // .#...................#.
        0b01100000000000000000110, // .##.................##.
        0b00010000000000000001000, // ...#...............#...
        0b00001110000000001110000, // ....###.........###....
        0b00000001111111110000000, // .......#########.......
    ], 23);
}

#[cfg(feature = "fill")]
mod fill {
    use super::{assert_bitmap_eq, plot_spans};
    use nano9_raster::{EllipseFill, Span};

    fn plot_fill<const H: usize>(spans: impl Iterator<Item = Span>, w: u32) -> [u32; H] {
        plot_spans(spans.map(|h| (h.x0, h.x1, h.y)), w)
    }

    /// Pico-8 `ovalfill(8, 8, 8, 8)`.
    #[test]
    fn pico_ovalfill_1x1() {
        #[rustfmt::skip]
        assert_bitmap_eq!(plot_fill::<1>(EllipseFill::from_rect((0, 0), (0, 0)), 1), [
            0b1, // #
        ], 1);
    }

    /// Pico-8 `ovalfill(16, 8, 20, 12)`.
    #[test]
    fn pico_ovalfill_5x5() {
        #[rustfmt::skip]
        assert_bitmap_eq!(plot_fill::<5>(EllipseFill::from_rect((0, 0), (4, 4)), 5), [
            0b01110, // .###.
            0b11111, // #####
            0b11111, // #####
            0b11111, // #####
            0b01110, // .###.
        ], 5);
    }

    /// Pico-8 `ovalfill(28, 8, 40, 16)`. Same pixels as `ovalfill(9, 56, 21, 64)`.
    #[test]
    fn pico_ovalfill_13x9() {
        #[rustfmt::skip]
        assert_bitmap_eq!(plot_fill::<9>(EllipseFill::from_rect((0, 0), (12, 8)), 13), [
            0b0000111110000, // ....#####....
            0b0011111111100, // ..#########..
            0b0111111111110, // .###########.
            0b1111111111111, // #############
            0b1111111111111, // #############
            0b1111111111111, // #############
            0b0111111111110, // .###########.
            0b0011111111100, // ..#########..
            0b0000111110000, // ....#####....
        ], 13);
    }

    /// Pico-8 `ovalfill(48, 8, 70, 20)`.
    #[test]
    fn pico_ovalfill_23x13() {
        #[rustfmt::skip]
        assert_bitmap_eq!(plot_fill::<13>(EllipseFill::from_rect((0, 0), (22, 12)), 23), [
            0b00000001111111110000000, // .......#########.......
            0b00001111111111111110000, // ....###############....
            0b00011111111111111111000, // ...#################...
            0b01111111111111111111110, // .#####################.
            0b01111111111111111111110, // .#####################.
            0b11111111111111111111111, // #######################
            0b11111111111111111111111, // #######################
            0b11111111111111111111111, // #######################
            0b01111111111111111111110, // .#####################.
            0b01111111111111111111110, // .#####################.
            0b00011111111111111111000, // ...#################...
            0b00001111111111111110000, // ....###############....
            0b00000001111111110000000, // .......#########.......
        ], 23);
    }
}
